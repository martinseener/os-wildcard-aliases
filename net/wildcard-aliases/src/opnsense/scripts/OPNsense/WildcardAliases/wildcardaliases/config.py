import ipaddress
import json
import re
from dataclasses import dataclass
from typing import Optional

from .matcher import Matcher

TABLE_NAME = re.compile(r'^[A-Za-z_][A-Za-z0-9_]{0,30}$')


class ConfigError(ValueError):
    pass


@dataclass(frozen=True)
class AliasConfig:
    name: str
    patterns: tuple
    inet: bool = True
    inet6: bool = True
    max_entries: int = 4096


@dataclass(frozen=True)
class Config:
    listen: tuple
    upstreams: tuple
    aliases: tuple
    upstream_timeout: float = 3.0
    # all optional: by default an address stays exactly as long as the DNS TTL says
    min_hold: int = 0
    grace: int = 0
    max_hold: Optional[int] = None
    fail_closed: bool = True
    verbose: bool = False
    cleanup_interval: int = 10
    state_interval: int = 60
    state_file: str = '/var/db/wildcardaliases/state.json'
    status_file: str = '/var/run/wildcardaliases/status.json'

    def hold_time(self, ttl):
        """ how long a learned address stays in its table """
        hold = max(ttl + self.grace, self.min_hold)
        return hold if self.max_hold is None else min(hold, self.max_hold)


def parse_address(value, default_port=53, allow_any_port=False):
    """ parse "host", "host:port", "[v6]:port" or "v6" into (host, port)

        allow_any_port permits port 0 (let the OS choose), only sensible for listen addresses
    """
    value = str(value).strip()
    if not value:
        raise ConfigError('empty address')
    host, port = value, default_port
    if value.startswith('['):
        end = value.find(']')
        if end < 0:
            raise ConfigError('invalid address %r' % value)
        host = value[1:end]
        rest = value[end + 1:]
        if rest:
            if not rest.startswith(':'):
                raise ConfigError('invalid address %r' % value)
            port = rest[1:]
    elif value.count(':') == 1:
        host, port = value.split(':')
    try:
        ipaddress.ip_address(host)
    except ValueError:
        raise ConfigError('invalid IP address %r (hostnames are not supported)' % host)
    try:
        port = int(port)
    except ValueError:
        raise ConfigError('invalid port in %r' % value)
    if not (0 if allow_any_port else 1) <= port < 65536:
        raise ConfigError('invalid port in %r' % value)
    return host, port


def _int(data, key, default, minimum=0):
    value = data.get(key)
    if value is None:
        return default
    try:
        value = int(value)
    except (TypeError, ValueError):
        raise ConfigError('%s must be an integer' % key)
    if value < minimum:
        raise ConfigError('%s must be >= %d' % (key, minimum))
    return value


def parse(data):
    """ build a Config from its JSON representation (as generated by the OPNsense template) """
    if not isinstance(data, dict):
        raise ConfigError('configuration must be a JSON object')

    listen = tuple(parse_address(item, allow_any_port=True) for item in (data.get('listen') or ['127.0.0.1:5354']))
    upstreams = tuple(parse_address(item) for item in (data.get('upstreams') or []))
    if not upstreams:
        raise ConfigError('at least one upstream is required')
    if set(listen) & set(upstreams):
        raise ConfigError('an upstream must not point to one of our own listen addresses')

    aliases = []
    seen = set()
    for item in data.get('aliases') or []:
        name = str(item.get('name', ''))
        if not TABLE_NAME.match(name):
            raise ConfigError('invalid table name %r' % name)
        if name in seen:
            raise ConfigError('duplicate table name %r' % name)
        seen.add(name)
        patterns = tuple(p.strip() for p in item.get('patterns') or [] if p.strip())
        if not patterns:
            raise ConfigError('table %s has no patterns' % name)
        for pattern in patterns:
            try:
                Matcher.parse(pattern)
            except ValueError as exc:
                raise ConfigError('table %s: %s' % (name, exc))
        alias = AliasConfig(
            name=name,
            patterns=patterns,
            inet=bool(item.get('inet', True)),
            inet6=bool(item.get('inet6', True)),
            max_entries=_int(item, 'max_entries', 4096, minimum=1),
        )
        if not (alias.inet or alias.inet6):
            raise ConfigError('table %s has neither IPv4 nor IPv6 enabled' % name)
        aliases.append(alias)

    fail_mode = data.get('fail_mode', 'closed')
    if fail_mode not in ('closed', 'open'):
        raise ConfigError('fail_mode must be "closed" or "open"')

    kwargs = {}
    for key in ('state_file', 'status_file'):
        if data.get(key):
            kwargs[key] = str(data[key])
    try:
        timeout = float(data.get('upstream_timeout', 3.0))
    except (TypeError, ValueError):
        raise ConfigError('upstream_timeout must be a number')
    if timeout <= 0:
        raise ConfigError('upstream_timeout must be positive')

    return Config(
        listen=listen,
        upstreams=upstreams,
        aliases=tuple(aliases),
        upstream_timeout=timeout,
        min_hold=_int(data, 'min_hold', 0),
        grace=_int(data, 'grace', 0),
        max_hold=_int(data, 'max_hold', None, minimum=1),
        fail_closed=fail_mode == 'closed',
        verbose=bool(data.get('verbose', False)),
        cleanup_interval=_int(data, 'cleanup_interval', 10, minimum=1),
        state_interval=_int(data, 'state_interval', 60, minimum=1),
        **kwargs
    )


def load(path):
    try:
        with open(path) as fhandle:
            data = json.load(fhandle)
    except (OSError, ValueError) as exc:
        raise ConfigError('unable to read %s: %s' % (path, exc))
    return parse(data)
